"""### **Runnable**

A Runnable is a unit of execution in the LangChain framework. It represents a specific task or operation that can be performed.
Examples of Runnables include data transformations, computations, or any other operation that can be expressed in the LangChain expression language.

**Example 1: [Runnable Lambdas](https://api.python.langchain.com/en/latest/runnables/langchain_core.runnables.base.RunnableLambda.html)**

The RunnableLambda is a LangChain abstraction that allows us to turn Python functions into pipe-compatible functions, similar to the Runnable class.
"""

# Importing the `RunnableLambda` class from the `langchain_core.runnables` module.
# This class allows you to create a runnable chain of actions from a lambda function.
from langchain_core.runnables import RunnableLambda

# Define a function that adds 5 to the input value.
def add_five(x):
    return x + 5

# Define a function that multiplies the input value by 2.
def multiply_by_two(x):
    return x * 2

# Wrap the functions with RunnableLambda to create a chain of operations.
# The output of `add_five` will be passed as input to `multiply_by_two`.
chain = RunnableLambda(add_five) | RunnableLambda(multiply_by_two)

chain.invoke(2)

# A RunnableSequence constructed using the `|` operator
# The sequence defines a pipeline where the output of each step is passed to the next one.

# The first step is a function that adds 1 to the input `x`
# The second step is a function that multiplies the result of the first step by 2

sequence = RunnableLambda(lambda x: x + 1) | RunnableLambda(lambda x: x * 2)

# Invoke the sequence with an initial input value of 1
# The steps in the sequence will be executed: 1 + 1 = 2, then 2 * 2 = 4
sequence.invoke(1)

# Define a lambda function `exmp` that takes two arguments `x` and `y`, and returns their sum.
exmp = lambda x, y: x + y

# Invoke the lambda function `exmp` with arguments 2 and 3.
# The result of 2 + 3 will be computed, which is 5.
exmp(2, 3)

"""**Example 2 : [RunnablePassthrough](https://api.python.langchain.com/en/latest/runnables/langchain_core.runnables.passthrough.RunnablePassthrough.html)** on its own allows you to pass inputs unchanged. This typically is **used in conjuction with [RunnableParallel](https://python.langchain.com/v0.1/docs/expression_language/interface/#parallelism)** to pass data through to a new key in the map."""

# Import the necessary classes from langchain_core.runnables
from langchain_core.runnables import RunnableParallel, RunnablePassthrough

# Define a `RunnableParallel` object.
# `RunnableParallel` allows running multiple functions (or lambdas) in parallel.
# Here, two tasks are defined:
# 1. `passed`: A `RunnablePassthrough` that simply passes the input as is without modifying it.
# 2. `modified`: A lambda function that takes an input `x` (assumed to be a dictionary) and multiplies the value of the key `"num"` by 4.
runnable = RunnableParallel(
    passed=RunnablePassthrough(),  # This step passes the input without modification.
    modified = lambda x: x["num"] * 4,  # This step multiplies the value associated with the key "num" by 4.
)

# Invoke the `runnable` object with an input dictionary containing the key "num" with a value of 2.
# The `RunnableParallel` object will execute the two defined tasks in parallel:
# 1. The `passed` task will pass the input dictionary as is.
# 2. The `modified` task will multiply the value of the "num" key (which is 2) by 4, resulting in 8.
result = runnable.invoke({"num": 2})

