# It uses the model to generate a response based on the prompt, where "{product}" will be replaced by "cup".
# The result will be the output of the language model after parsing it as a string using `StrOutputParser()`.
result = chain1.invoke(product)  # Invoking the chain with the product "cup"
print(result)  # Output the result of the chain, which is the model's response.

