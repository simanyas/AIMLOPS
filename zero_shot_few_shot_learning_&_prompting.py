# Load a pre-trained question-answering pipeline using the `transformers` library.
question_answerer = pipeline("question-answering")

# Perform question answering by providing a question and a context.
result = question_answerer(question="Where is tea native to?", context=context)

# Print only the extracted answer from the result.
print(result['answer'])

# Define a list of questions to be answered based on the given context.
questions = ["Where is tea native to?",
             "When was tea discovered?",
             "What is the species name for tea?"]

# Use the question-answering pipeline to extract answers for all questions.
results = question_answerer(question=questions, context=context)

# Loop through each question and its corresponding answer.
for q, r in zip(questions, results):
    print(q, "\n>> " + r['answer'])

